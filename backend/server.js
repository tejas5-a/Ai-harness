/**
 * Altron Code AI - Persistent Background Worker & REST API
 * Supports autonomous multi-step coding jobs running independently of mobile clients.
 */

const express = require('express');
const cors = require('cors');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const app = express();
const PORT = process.env.PORT || 3000;
const AUTH_TOKEN = process.env.ALTRON_AUTH_TOKEN || 'altron-secret-worker-key-2026';
const DATA_DIR = path.join(__dirname, 'data');
const TASKS_FILE = path.join(DATA_DIR, 'tasks.json');
const WORKSPACE_DIR = path.join(DATA_DIR, 'workspaces');

if (!fs.existsSync(DATA_DIR)) fs.mkdirSync(DATA_DIR, { recursive: true });
if (!fs.existsSync(WORKSPACE_DIR)) fs.mkdirSync(WORKSPACE_DIR, { recursive: true });

app.use(cors());
app.use(express.json({ limit: '25mb' }));

// Persistent Task Store
let tasks = [];
try {
  if (fs.existsSync(TASKS_FILE)) {
    tasks = JSON.parse(fs.readFileSync(TASKS_FILE, 'utf8'));
  }
} catch (e) {
  tasks = [];
}

function saveTasksToDisk() {
  try {
    fs.writeFileSync(TASKS_FILE, JSON.stringify(tasks, null, 2), 'utf8');
  } catch (err) {
    console.error('Failed to persist tasks:', err.message);
  }
}

// Authentication Middleware
function authenticate(req, res, next) {
  const authHeader = req.headers.authorization || '';
  const token = authHeader.replace(/^Bearer\s+/i, '');
  const apiKey = req.headers['x-api-key'];

  if (token === AUTH_TOKEN || apiKey === AUTH_TOKEN || !process.env.ALTRON_AUTH_TOKEN) {
    return next();
  }
  return res.status(401).json({ error: 'Unauthorized: Invalid or missing authentication token' });
}

// Concurrency & Worker Queue
let activeJobsCount = 0;
const MAX_CONCURRENT_JOBS = 2;
const activeAbortControllers = new Map();

function logTask(task, level, message) {
  const entry = { timestamp: Date.now(), level, message };
  task.logs.push(entry);
  console.log(`[Task ${task.id.slice(0, 8)}] [${level}] ${message}`);
  saveTasksToDisk();
}

async function processQueue() {
  if (activeJobsCount >= MAX_CONCURRENT_JOBS) return;

  const nextTask = tasks.find(t => t.state === 'QUEUED');
  if (!nextTask) return;

  activeJobsCount++;
  executeJob(nextTask).finally(() => {
    activeJobsCount--;
    processQueue();
  });
}

async function executeJob(task) {
  task.state = 'RUNNING';
  task.startedAt = task.startedAt || Date.now();
  task.progressPercent = 10;
  task.currentOperation = 'Preparing project workspace...';
  logTask(task, 'STEP', 'Stage 1/5: Initializing secure project workspace.');

  const abortController = new AbortController();
  activeAbortControllers.set(task.id, abortController);

  try {
    const projectWorkspace = path.join(WORKSPACE_DIR, task.projectId || 'default');
    if (!fs.existsSync(projectWorkspace)) fs.mkdirSync(projectWorkspace, { recursive: true });

    // Step 2: Planning & AI Generation
    if (abortController.signal.aborted) throw new Error('Task was cancelled');
    task.progressPercent = 35;
    task.currentOperation = `Formulating architecture plan with ${task.modelId}...`;
    logTask(task, 'STEP', `Stage 2/5: Streaming AI coding reasoning via ${task.providerType} (${task.modelId}).`);

    // Simulated / Model inference pipeline
    const generatedChanges = [
      {
        relativePath: 'src/main.js',
        isCreated: true,
        newContent: '// Generated by Altron Code Background Worker\nconsole.log("Background Task Executed Successfully");\n'
      }
    ];

    // Step 3: Approval Check if destructive
    if (task.requiresApproval && task.state !== 'RUNNING') {
      task.state = 'WAITING_APPROVAL';
      task.progressPercent = 60;
      task.currentOperation = 'Awaiting user confirmation to write changes.';
      logTask(task, 'WARN', 'Task paused: waiting for client approval.');
      saveTasksToDisk();
      return;
    }

    // Step 4: Applying Changes
    if (abortController.signal.aborted) throw new Error('Task was cancelled');
    task.progressPercent = 80;
    task.currentOperation = 'Applying verified changes to project...';
    logTask(task, 'STEP', 'Stage 4/5: Writing files into project workspace.');

    for (const change of generatedChanges) {
      const fullPath = path.join(projectWorkspace, change.relativePath);
      const dir = path.dirname(fullPath);
      if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(fullPath, change.newContent, 'utf8');
      task.changes.push(change);
      logTask(task, 'INFO', `Written ${change.relativePath} (${change.newContent.length} bytes).`);
    }

    // Step 5: Verification & Completion
    task.progressPercent = 100;
    task.state = 'COMPLETED';
    task.completedAt = Date.now();
    task.currentOperation = 'Completed successfully.';
    logTask(task, 'SUCCESS', `Task completed! Successfully updated ${generatedChanges.length} files.`);
    saveTasksToDisk();
  } catch (err) {
    if (abortController.signal.aborted || err.message === 'Task was cancelled') {
      task.state = 'CANCELLED';
      task.currentOperation = 'Cancelled by user.';
      logTask(task, 'WARN', 'Task cancelled.');
    } else {
      task.state = 'FAILED';
      task.errorMessage = err.message;
      task.currentOperation = `Failed: ${err.message}`;
      logTask(task, 'ERROR', `Task execution failed: ${err.message}`);
    }
    task.completedAt = Date.now();
    saveTasksToDisk();
  } finally {
    activeAbortControllers.delete(task.id);
  }
}

// ==================== REST ENDPOINTS ====================

// Health Check
app.get('/health', (req, res) => {
  res.json({
    status: 'online',
    timestamp: Date.now(),
    activeWorkers: activeJobsCount,
    maxConcurrency: MAX_CONCURRENT_JOBS,
    totalTasks: tasks.length
  });
});

// List all tasks
app.get('/api/tasks', authenticate, (req, res) => {
  res.json(tasks);
});

// Submit a new task
app.post('/api/tasks', authenticate, (req, res) => {
  const { title, description, prompt, projectId, projectName, providerType, modelId, requiresApproval } = req.body;

  const newTask = {
    id: crypto.randomUUID(),
    title: title || 'Background Coding Task',
    description: description || '',
    prompt: prompt || title || '',
    projectId: projectId || 'default',
    projectName: projectName || 'Default Project',
    providerType: providerType || 'GEMINI',
    modelId: modelId || 'gemini-2.0-flash',
    state: 'QUEUED',
    progressPercent: 0,
    currentOperation: 'Queued in backend worker queue',
    createdAt: Date.now(),
    startedAt: null,
    completedAt: null,
    logs: [
      { timestamp: Date.now(), level: 'INFO', message: 'Task submitted to backend worker.' }
    ],
    changes: [],
    requiresApproval: Boolean(requiresApproval),
    errorMessage: null,
    retryCount: 0,
    maxRetries: 3
  };

  tasks.unshift(newTask);
  saveTasksToDisk();
  processQueue();

  res.status(201).json(newTask);
});

// Get task status and logs
app.get('/api/tasks/:id', authenticate, (req, res) => {
  const task = tasks.find(t => t.id === req.params.id);
  if (!task) return res.status(404).json({ error: 'Task not found' });
  res.json(task);
});

// Cancel a task
app.post('/api/tasks/:id/cancel', authenticate, (req, res) => {
  const task = tasks.find(t => t.id === req.params.id);
  if (!task) return res.status(404).json({ error: 'Task not found' });

  const controller = activeAbortControllers.get(task.id);
  if (controller) {
    controller.abort();
  } else if (task.state === 'QUEUED') {
    task.state = 'CANCELLED';
    task.completedAt = Date.now();
    logTask(task, 'WARN', 'Queued task cancelled before execution.');
  }

  saveTasksToDisk();
  res.json({ message: 'Task cancelled', task });
});

// Retry a task
app.post('/api/tasks/:id/retry', authenticate, (req, res) => {
  const task = tasks.find(t => t.id === req.params.id);
  if (!task) return res.status(404).json({ error: 'Task not found' });

  task.state = 'QUEUED';
  task.progressPercent = 0;
  task.currentOperation = 'Re-queued for execution.';
  task.retryCount = (task.retryCount || 0) + 1;
  task.errorMessage = null;
  logTask(task, 'INFO', `Task re-queued (retry attempt ${task.retryCount}).`);

  saveTasksToDisk();
  processQueue();
  res.json({ message: 'Task re-queued', task });
});

// Approve pending action
app.post('/api/tasks/:id/approve', authenticate, (req, res) => {
  const task = tasks.find(t => t.id === req.params.id);
  if (!task) return res.status(404).json({ error: 'Task not found' });

  if (task.state === 'WAITING_APPROVAL') {
    task.state = 'RUNNING';
    task.requiresApproval = false;
    logTask(task, 'INFO', 'Action approved by user. Resuming.');
    executeJob(task);
  }

  saveTasksToDisk();
  res.json({ message: 'Action approved', task });
});

app.listen(PORT, () => {
  console.log(`Altron Code Backend Worker running on port ${PORT}`);
  processQueue();
});
